// Compiles src/content/articles/*.md into src/app/pages/knowledge/generated:
// index.ts with the metadata of every article (newest first) and one module of
// pre-rendered HTML per article, loaded on demand by the article page. Invalid
// front matter fails the build. Runs as the npm `pre*` scripts.
//
//   node scripts/build-articles.mjs                  compile once
//   node scripts/build-articles.mjs --watch <cmd...>  compile, run <cmd> and recompile on changes
import { spawn } from 'node:child_process';
import { mkdirSync, readdirSync, readFileSync, rmSync, watch, writeFileSync } from 'node:fs';
import { compileArticle } from '../src/content/compile-article.ts';

const SOURCE_DIR = new URL('../src/content/articles/', import.meta.url);
const OUT_DIR = new URL('../src/app/pages/knowledge/generated/', import.meta.url);
const HEADER =
  '// Generated by scripts/build-articles.mjs from src/content/articles. Do not edit.\n';

function build() {
  const articles = readdirSync(SOURCE_DIR)
    .filter((name) => name.endsWith('.md'))
    .map((name) => compileArticle(name, readFileSync(new URL(name, SOURCE_DIR), 'utf8')))
    .sort(
      (a, b) =>
        b.metadata.publishedAt.localeCompare(a.metadata.publishedAt) ||
        a.metadata.slug.localeCompare(b.metadata.slug),
    );

  const duplicate = articles.find(
    (article, i) => articles.findIndex((a) => a.metadata.slug === article.metadata.slug) !== i,
  );
  if (duplicate) {
    throw new Error(`Duplicate article slug: ${duplicate.metadata.slug}`);
  }

  const files = new Map([
    [
      'index.ts',
      HEADER +
        `import type { ArticleMetadata } from '../articles';\n\n` +
        `export const ARTICLES: readonly ArticleMetadata[] = ${JSON.stringify(
          articles.map((a) => a.metadata),
          null,
          2,
        )};\n\n` +
        `export const ARTICLE_HTML: Record<string, () => Promise<{ default: string }>> = {\n` +
        articles
          .map(({ metadata: { slug } }) => `  '${slug}': () => import('./${slug}'),\n`)
          .join('') +
        `};\n`,
    ],
    ...articles.map(({ metadata, html }) => [
      `${metadata.slug}.ts`,
      `${HEADER}export default ${JSON.stringify(html)};\n`,
    ]),
  ]);

  mkdirSync(OUT_DIR, { recursive: true });
  for (const name of readdirSync(OUT_DIR)) {
    if (!files.has(name)) {
      rmSync(new URL(name, OUT_DIR));
    }
  }
  for (const [name, content] of files) {
    // Rewriting unchanged files would make `ng serve` rebuild for nothing.
    const file = new URL(name, OUT_DIR);
    if (readIfExists(file) !== content) {
      writeFileSync(file, content);
    }
  }
  console.log(`Compiled ${articles.length} articles into ${OUT_DIR.pathname}`);
}

function readIfExists(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return undefined;
  }
}

const watchIndex = process.argv.indexOf('--watch');
if (watchIndex === -1) {
  build();
} else {
  // A broken article must not stop the dev server: report it and keep watching.
  const rebuild = () => {
    try {
      build();
    } catch (error) {
      console.error(`\x1b[31mArticles: ${error.message}\x1b[0m`);
    }
  };
  rebuild();

  let timer;
  watch(SOURCE_DIR, () => {
    clearTimeout(timer);
    timer = setTimeout(rebuild, 100);
  });

  const command = process.argv.slice(watchIndex + 1);
  if (command.length > 0) {
    const child = spawn(command.join(' '), { stdio: 'inherit', shell: true });
    child.on('exit', (code, signal) => process.exit(code ?? (signal ? 1 : 0)));
  }
}
